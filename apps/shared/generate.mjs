/* Emits every derived brand file from tokens.json and the procedural orb. Safe to re-run; outputs are deterministic.
 *   node apps/shared/generate.mjs
 */
import { mkdirSync, writeFileSync, existsSync, readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { renderOrb, padTo, encodePNG, encodeICO, encodeICNS } from './icons.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const tokens = JSON.parse(readFileSync(new URL('./tokens.json', import.meta.url), 'utf8'));
const out = (rel, data) => {
  const p = join(root, rel);
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, data);
  return rel;
};
const png = (size, o) => encodePNG(renderOrb(size, o));
const written = [];

// ---- PWA / web icons (public/icons) ----
written.push(out('public/icons/icon-180.png', png(180, { corner: 0, radius: 0.36 }))); // iOS rounds it itself
written.push(out('public/icons/icon-192.png', png(192, { corner: 0, radius: 0.36 })));
written.push(out('public/icons/icon-512.png', png(512, { corner: 0, radius: 0.36 })));
// maskable: the OS crops to a circle or squircle, so the orb stays inside the central 80% safe zone
written.push(out('public/icons/icon-maskable-192.png', png(192, { corner: 0, radius: 0.28 })));
written.push(out('public/icons/icon-maskable-512.png', png(512, { corner: 0, radius: 0.28 })));
// monochrome: Android 13 themed icons tint this one
written.push(out('public/icons/icon-mono-512.png', png(512, { bg: null, radius: 0.34, mono: [0, 0, 0] })));

// ---- desktop (Electron) ----
const dFrames = [16, 24, 32, 48, 64, 128, 256, 512, 1024].map((size) => ({ size, png: png(size, { corner: 0.22, radius: 0.34 }) }));
const dBy = (s) => dFrames.find((f) => f.size === s).png;
written.push(out('apps/desktop/build/icon.png', dBy(512)));
written.push(out('apps/desktop/build/icon.ico', encodeICO(dFrames.filter((f) => f.size <= 256))));
written.push(out('apps/desktop/build/icon.icns', encodeICNS(dFrames)));
written.push(out('apps/desktop/assets/tray.png', png(32, { bg: null, radius: 0.46 })));
written.push(out('apps/desktop/assets/trayTemplate.png', png(22, { bg: null, radius: 0.46, mono: [0, 0, 0] })));
written.push(out('apps/desktop/assets/trayTemplate@2x.png', png(44, { bg: null, radius: 0.46, mono: [0, 0, 0] })));
written.push(out('apps/desktop/assets/tray-live.png', png(32, { bg: null, radius: 0.46, from: '#B23A2E', to: '#B23A2E' })));

// ---- extension ----
for (const s of [16, 32, 48, 128]) written.push(out(`apps/extension/icons/icon-${s}.png`, png(s, { bg: null, radius: 0.46 })));

// ---- tokens as CSS / JSON for each wrapper ----
const kebab = (k) => k.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase());
const cssVars = (obj, prefix) => Object.entries(obj).map(([k, v]) => `  --${prefix}-${kebab(k)}: ${v};`).join('\n');
const css = `/* generated by apps/shared/generate.mjs from tokens.json. Do not edit. */
:root {
${cssVars(tokens.color, 'color')}
  --orb-from: ${tokens.orb.from};
  --orb-to: ${tokens.orb.to};
  --radius-card: ${tokens.radius.card}px;
  --radius-button: ${tokens.radius.button}px;
  --shadow-card: ${tokens.shadow.card};
  --font-sans: ${tokens.font.sans};
  --font-display: ${tokens.font.display};
}
@media (prefers-color-scheme: dark) {
  :root {
${cssVars(tokens.dark, 'color').replace(/^ {2}/gm, '    ')}
  }
}
`;
written.push(out('apps/extension/src/theme.css', css));
const slim = { color: tokens.color, dark: tokens.dark, orb: tokens.orb, app: tokens.app };
written.push(out('apps/desktop/src/theme.json', JSON.stringify(slim, null, 2) + '\n'));
written.push(out('apps/mobile/theme.json', JSON.stringify(slim, null, 2) + '\n'));

// ---- Android / iOS brand (only once `cap add` has made the native projects) ----
const droid = 'apps/mobile/android/app/src/main/res';
if (existsSync(join(root, droid))) {
  const legacy = { mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 };
  for (const [d, s] of Object.entries(legacy)) {
    written.push(out(`${droid}/mipmap-${d}/ic_launcher.png`, png(s, { corner: 0.22, radius: 0.34 })));
    written.push(out(`${droid}/mipmap-${d}/ic_launcher_round.png`, png(s, { corner: 0.5, radius: 0.34 })));
    // adaptive foreground: 108dp canvas, orb inside the 66dp safe zone
    const fg = Math.round((s / 48) * 108);
    const orb = renderOrb(Math.round(fg * 0.61), { bg: null, radius: 0.5 });
    written.push(out(`${droid}/mipmap-${d}/ic_launcher_foreground.png`, encodePNG(padTo(orb, fg, 0.61))));
  }
  written.push(out(`${droid}/values/ic_launcher_background.xml`, `<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <color name="ic_launcher_background">${tokens.color.canvas}</color>\n</resources>\n`));
  written.push(out(`${droid}/values/stay_colors.xml`, `<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <color name="stayCanvas">${tokens.color.canvas}</color>\n    <color name="stayAccent">${tokens.color.accent}</color>\n    <color name="stayInk">${tokens.color.ink}</color>\n</resources>\n`));
  // launch splash: the canvas colour with the orb in the middle (replaces Capacitor's default splash.png in every density)
  written.push(out(`${droid}/drawable/splash_orb.png`, png(480, { bg: null, radius: 0.4 })));
  written.push(out(`${droid}/drawable/splash.xml`, `<?xml version="1.0" encoding="utf-8"?>
<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item android:drawable="@color/stayCanvas" />
    <item>
        <bitmap android:gravity="center" android:src="@drawable/splash_orb" />
    </item>
</layer-list>
`));
  // status-bar icon for notifications: Android wants a flat white silhouette
  for (const [d, s] of Object.entries({ mdpi: 24, hdpi: 36, xhdpi: 48, xxhdpi: 72, xxxhdpi: 96 })) {
    written.push(out(`${droid}/drawable-${d}/ic_stat_stay.png`, png(s, { bg: null, radius: 0.46, mono: [255, 255, 255] })));
  }
}
const ios = 'apps/mobile/ios/App/App/Assets.xcassets';
if (existsSync(join(root, ios))) {
  written.push(out(`${ios}/AppIcon.appiconset/AppIcon-512@2x.png`, png(1024, { corner: 0, radius: 0.34 })));
  written.push(out(`${ios}/Splash.imageset/splash-2732x2732.png`, png(1024, { corner: 0, radius: 0.2 })));
}

console.log(`wrote ${written.length} files`);
for (const w of written) console.log('  ' + w);
