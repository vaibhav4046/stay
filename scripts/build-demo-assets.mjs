#!/usr/bin/env node
/**
 * Builds the landing-page demo from a real recorded call (scripts/real-voice-e2e.mjs, run WITHOUT NO_VIDEO):
 *   docs/evidence/real-e2e/demo-silent.webm + captions.json  ->  public/demo/stay-demo.{mp4,vtt}, stay-demo-poster.jpg,
 *   src/components/landing/demoData.ts (chapters and transcript, identical to the captions).
 * The recording has no sound track (Chromium cannot record page audio); the words are in the captions. Needs ffmpeg.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const IN = 'docs/evidence/real-e2e';
const { recStart, callEndAt, caps } = JSON.parse(readFileSync(`${IN}/captions.json`, 'utf8'));
const lead = 0.4; // captions appear just before the line lands
const clean = (t) => t.replace(/\s+/g, ' ').replace(/^Scratch that/, '').trim();

const rows = caps
  .map((c) => ({ who: c.who, text: clean(c.text), at: (c.t - recStart) / 1000 - lead, typed: c.t > callEndAt }))
  .filter((r) => r.text)
  .sort((a, b) => a.at - b.at);

const label = (r) => (r.who === 'stay' ? 'Stay' : r.typed ? 'Typed' : 'Simulated voice');
const cues = rows.map((r, i) => {
  const start = Math.max(0.5, r.at);
  const next = rows[i + 1] ? rows[i + 1].at - 0.1 : start + 6;
  const end = Math.min(next, start + Math.max(3, r.text.split(' ').length * 0.42));
  return { start, end: Math.max(end, start + 0.8), text: `${label(r)}: ${r.text}`, row: r };
});

const ts = (s) => {
  const h = Math.floor(s / 3600), m = Math.floor((s % 3600) / 60), sec = s % 60;
  return `${String(h).padStart(2, '0')}:${String(m).padStart(2, '0')}:${sec.toFixed(3).padStart(6, '0')}`;
};
const clock = (s) => `${Math.floor(s / 60)}:${String(Math.floor(s % 60)).padStart(2, '0')}`;

mkdirSync('public/demo', { recursive: true });
writeFileSync('public/demo/stay-demo.vtt', 'WEBVTT\n\n' + cues.map((c, i) => `${i + 1}\n${ts(c.start)} --> ${ts(c.end)}\n${c.text}\n`).join('\n'));

// chapters start exactly where a caption starts
const pick = (re, from = 0) => cues.findIndex((c, i) => i >= from && re(c.row));
const chapterDefs = [
  ['Hello', 0],
  ['You say it', pick((r) => r.who === 'person' && !r.typed)],
  ['Stay answers', pick((r) => r.who === 'stay', 1)],
  ['Talk over it', pick((r) => r.who === 'person' && /^wait|stop/i.test(r.text))],
  ['Switch to Spanish', pick((r) => r.who === 'person' && /[¿¡ñáéíóú]|necesito/i.test(r.text))],
  ['Ask for a panel', pick((r) => r.typed)],
].filter(([, i]) => i >= 0);
const seen = new Set();
const chapters = chapterDefs.filter(([, i]) => !seen.has(i) && seen.add(i)).sort((a, b) => a[1] - b[1]).map(([name, i]) => ({ t: Number(cues[i].start.toFixed(3)), label: name }));

const dataTs = `/** Generated by scripts/build-demo-assets.mjs from a real recorded call. Do not edit by hand. */
export const CHAPTERS = ${JSON.stringify(chapters, null, 2)} as const;

/** The captions of public/demo/stay-demo.vtt as text, for the transcript under the player (tests/unit/landing.test.ts keeps them identical). */
export const TRANSCRIPT = ${JSON.stringify(cues.map((c) => ({ start: clock(c.start), text: c.text })), null, 2)};
`;
writeFileSync('src/components/landing/demoData.ts', dataTs);

const ff = (args) => execFileSync('ffmpeg', ['-y', '-loglevel', 'error', ...args], { stdio: 'inherit' });
ff(['-i', `${IN}/demo-silent.webm`, '-vf', 'scale=1280:720,fps=25', '-c:v', 'libx264', '-preset', 'slow', '-crf', '27', '-pix_fmt', 'yuv420p', '-an', '-movflags', '+faststart', 'public/demo/stay-demo.mp4']);
const posterAt = Math.max(1, (cues.find((c) => c.row.who === 'stay')?.start ?? 3) + 1.2);
ff(['-ss', String(posterAt), '-i', 'public/demo/stay-demo.mp4', '-frames:v', '1', '-q:v', '3', 'public/demo/stay-demo-poster.jpg']);
const dur = execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', 'public/demo/stay-demo.mp4']).toString().trim();
console.log(`demo built: ${cues.length} captions, ${chapters.length} chapters, ${Number(dur).toFixed(1)} s`);
