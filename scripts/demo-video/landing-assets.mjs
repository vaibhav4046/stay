#!/usr/bin/env node
/**
 * After story.mjs: the landing page's film file (1280x720, small enough to start by itself) and its transcript, taken from the film's own
 * captions so the two can never differ.
 *
 *   node scripts/demo-video/landing-assets.mjs     -> public/demo/stay-story-film-web.mp4, src/components/landing/demoData.ts
 */
import fs from 'node:fs';
import { execFileSync } from 'node:child_process';

const vtt = fs.readFileSync('public/demo/stay-story-film.vtt', 'utf8');
const cues = [...vtt.matchAll(/(\d\d):(\d\d):(\d\d\.\d{3}) --> [^\n]*\n([^\n]+)/g)].map((m) => ({ s: Number(m[1]) * 3600 + Number(m[2]) * 60 + Number(m[3]), text: m[4].trim() }));
if (!cues.length) throw new Error('no captions found in public/demo/stay-story-film.vtt');
const clock = (s) => `${Math.floor(s / 60)}:${String(Math.floor(s % 60)).padStart(2, '0')}`;
fs.writeFileSync(
  'src/components/landing/demoData.ts',
  `/** Generated by scripts/demo-video/landing-assets.mjs from public/demo/stay-story-film.vtt (tests/unit/landing.test.ts keeps them identical). Do not edit by hand. */\nexport const TRANSCRIPT = ${JSON.stringify(cues.map((c) => ({ start: clock(c.s), text: c.text })), null, 2)};\n`,
);
if (!fs.existsSync('public/demo/stay-story-film-web.mp4')) execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-i', 'public/demo/stay-story-film.mp4', '-vf', 'scale=1280:720', '-c:v', 'libx264', '-preset', 'slow', '-crf', '27', '-pix_fmt', 'yuv420p', '-c:a', 'aac', '-b:a', '96k', '-movflags', '+faststart', 'public/demo/stay-story-film-web.mp4'], { stdio: 'inherit' });
console.log(`landing assets: ${cues.length} captions, ${(fs.statSync('public/demo/stay-story-film-web.mp4').size / 1e6).toFixed(1)} MB`);
